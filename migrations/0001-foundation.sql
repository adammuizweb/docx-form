CREATE TABLE IF NOT EXISTS `dxf_templates` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `title` VARCHAR(191) NOT NULL,
  `slug` VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `description` TEXT DEFAULT NULL,
  `status` VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'draft',
  `identity_mode` VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `current_version_id` BIGINT UNSIGNED DEFAULT NULL,
  `version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_by` BIGINT UNSIGNED NOT NULL,
  `updated_by` BIGINT UNSIGNED NOT NULL,
  `created_at_utc` DATETIME NOT NULL,
  `updated_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `dxf_template_slug_uq` (`slug`),
  KEY `dxf_template_public` (`status`,`slug`),
  KEY `dxf_template_current_version` (`current_version_id`),
  CONSTRAINT `dxf_template_status_ck` CHECK (`status` IN ('draft','published','archived')),
  CONSTRAINT `dxf_template_identity_ck` CHECK (`identity_mode` IN ('email_otp','self_declared'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dxf_template_versions` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `template_id` BIGINT UNSIGNED NOT NULL,
  `revision` INT UNSIGNED NOT NULL,
  `display_title` VARCHAR(191) NOT NULL,
  `display_description` TEXT DEFAULT NULL,
  `descriptor_json` JSON NOT NULL,
  `descriptor_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `docx_storage_name` CHAR(53) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `docx_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `docx_size` BIGINT UNSIGNED NOT NULL,
  `source_pdf_storage_name` CHAR(52) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `source_pdf_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `source_pdf_size` BIGINT UNSIGNED DEFAULT NULL,
  `source_pdf_inline_validated` TINYINT(1) NOT NULL DEFAULT 0,
  `allow_source_view` TINYINT(1) NOT NULL DEFAULT 0,
  `allow_source_download` TINYINT(1) NOT NULL DEFAULT 0,
  `allow_docx_download` TINYINT(1) NOT NULL DEFAULT 1,
  `allow_print` TINYINT(1) NOT NULL DEFAULT 1,
  `allow_pdf` TINYINT(1) NOT NULL DEFAULT 0,
  `created_by` BIGINT UNSIGNED NOT NULL,
  `created_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `dxf_version_revision_uq` (`template_id`,`revision`),
  CONSTRAINT `dxf_version_template_fk` FOREIGN KEY (`template_id`) REFERENCES `dxf_templates` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_version_toggles_ck` CHECK (`source_pdf_inline_validated` IN (0,1) AND `allow_source_view` IN (0,1) AND `allow_source_download` IN (0,1) AND `allow_docx_download` IN (0,1) AND `allow_print` IN (0,1) AND `allow_pdf` IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dxf_submissions` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `public_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `template_id` BIGINT UNSIGNED NOT NULL,
  `template_version_id` BIGINT UNSIGNED NOT NULL,
  `identity_mode` VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `identity_json` JSON NOT NULL,
  `identity_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `values_json` JSON NOT NULL,
  `values_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `idempotency_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `receipt_token_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `receipt_expires_at_utc` DATETIME NOT NULL,
  `receipt_revoked_at_utc` DATETIME DEFAULT NULL,
  `status` VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  `review_reason` VARCHAR(1000) DEFAULT NULL,
  `reviewed_by` BIGINT UNSIGNED DEFAULT NULL,
  `reviewed_at_utc` DATETIME DEFAULT NULL,
  `output_docx_storage_name` CHAR(53) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `output_docx_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `output_pdf_storage_name` CHAR(52) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `output_pdf_sha256` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `output_generated_at_utc` DATETIME DEFAULT NULL,
  `version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at_utc` DATETIME NOT NULL,
  `updated_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `dxf_submission_public_uq` (`public_id`),
  UNIQUE KEY `dxf_submission_receipt_uq` (`receipt_token_hash`),
  UNIQUE KEY `dxf_submission_idempotency_uq` (`template_id`,`idempotency_hash`),
  KEY `dxf_submission_queue` (`status`,`created_at_utc`,`id`),
  KEY `dxf_submission_receipt_expiry` (`receipt_expires_at_utc`,`receipt_revoked_at_utc`,`id`),
  KEY `dxf_submission_output_retention` (`output_generated_at_utc`,`id`),
  KEY `dxf_submission_version` (`template_version_id`),
  CONSTRAINT `dxf_submission_template_fk` FOREIGN KEY (`template_id`) REFERENCES `dxf_templates` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_submission_version_fk` FOREIGN KEY (`template_version_id`) REFERENCES `dxf_template_versions` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_submission_status_ck` CHECK (`status` IN ('pending','approved','rejected'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dxf_otp_challenges` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `public_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `template_id` BIGINT UNSIGNED NOT NULL,
  `template_version_id` BIGINT UNSIGNED NOT NULL,
  `token_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `email` VARCHAR(254) NOT NULL,
  `code_hash` VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `attempt_count` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `max_attempts` TINYINT UNSIGNED NOT NULL,
  `expires_at_utc` DATETIME NOT NULL,
  `verified_at_utc` DATETIME DEFAULT NULL,
  `used_at_utc` DATETIME DEFAULT NULL,
  `invalidated_at_utc` DATETIME DEFAULT NULL,
  `created_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `dxf_otp_public_uq` (`public_id`),
  UNIQUE KEY `dxf_otp_token_uq` (`token_hash`),
  KEY `dxf_otp_expiry` (`expires_at_utc`),
  KEY `dxf_otp_resend` (`template_id`,`email`,`created_at_utc`,`id`),
  KEY `dxf_otp_version` (`template_version_id`),
  CONSTRAINT `dxf_otp_template_fk` FOREIGN KEY (`template_id`) REFERENCES `dxf_templates` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_otp_version_fk` FOREIGN KEY (`template_version_id`) REFERENCES `dxf_template_versions` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dxf_submission_events` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `submission_id` BIGINT UNSIGNED DEFAULT NULL,
  `template_id` BIGINT UNSIGNED NOT NULL,
  `template_version_id` BIGINT UNSIGNED NOT NULL,
  `challenge_public_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `event_key` VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `actor_user_id` BIGINT UNSIGNED DEFAULT NULL,
  `ip_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `user_agent_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `metadata_json` JSON NOT NULL,
  `dedupe_key` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `created_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  KEY `dxf_event_submission` (`submission_id`,`id`),
  KEY `dxf_event_template` (`template_id`,`created_at_utc`,`id`),
  UNIQUE KEY `dxf_event_dedupe_uq` (`dedupe_key`),
  KEY `dxf_event_version` (`template_version_id`),
  CONSTRAINT `dxf_event_submission_fk` FOREIGN KEY (`submission_id`) REFERENCES `dxf_submissions` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_event_template_fk` FOREIGN KEY (`template_id`) REFERENCES `dxf_templates` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `dxf_event_version_fk` FOREIGN KEY (`template_version_id`) REFERENCES `dxf_template_versions` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dxf_rate_limits` (
  `subject_hash` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `action_key` VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `bucket_index` BIGINT UNSIGNED NOT NULL,
  `request_count` INT UNSIGNED NOT NULL DEFAULT 1,
  `expires_at_utc` DATETIME NOT NULL,
  PRIMARY KEY (`subject_hash`,`action_key`,`bucket_index`),
  KEY `dxf_rate_expiry` (`expires_at_utc`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
